// Which blocks unlock at which level index (0-based).
const UNLOCK = [[0, 'fwd', 'left', 'right'], [3, 'toggle'], [4, 'jump'], [6, 'repeat'], [12, 'if'], [13, 'ifelse'], [14, 'while'], [18, 'call'], [21, 'set', 'change']];
export function blocksFor(i) {
  const out = [];
  for (const [at, ...b] of UNLOCK) if (i >= at) out.push(...b);
  return out;
}
export const NEW_AT = Object.fromEntries(UNLOCK.map(([at, ...b]) => [at, b]));
